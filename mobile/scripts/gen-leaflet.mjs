// Copies Leaflet's JS + CSS into src/lib/leafletBundle.ts so the in-app map
// works without internet (the WebView loads it inline instead of from a CDN).
// Run after upgrading leaflet: `npm run gen:leaflet`
import fs from "node:fs";

const js = fs.readFileSync("node_modules/leaflet/dist/leaflet.js", "utf8");
const css = fs.readFileSync("node_modules/leaflet/dist/leaflet.css", "utf8");
const version = JSON.parse(fs.readFileSync("node_modules/leaflet/package.json", "utf8")).version;

fs.writeFileSync(
  "src/lib/leafletBundle.ts",
  `// AUTO-GENERATED by scripts/gen-leaflet.mjs from leaflet@${version}. Do not edit.\n` +
    `/* eslint-disable */\n` +
    `export const LEAFLET_JS = ${JSON.stringify(js)};\n` +
    `export const LEAFLET_CSS = ${JSON.stringify(css)};\n`,
);
console.log(`leafletBundle.ts written (leaflet ${version}, ${Math.round((js.length + css.length) / 1024)} KB)`);
